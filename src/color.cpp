enum class Color{
    /* This enum class serves to easily distinguish colors without using strings or other data types.
     * It contains generalized names of colors used in the game.
     * More colors can be added later.
     * Exact RGB values of each color are defined by the interface palette.
     */
    nullcolor,  //Empty case
    cyan,    // Line
    yellow,  // Square
    purple,  // T-shape
    green,   // S-shape (left)
    red,     // Z-shape (right)
    orange,  // L-shape (right)
    blue,    // J-shape (left)
};
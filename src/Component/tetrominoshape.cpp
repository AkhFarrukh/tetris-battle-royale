enum class TetrominoShape {
    /* This enum class serves to distinguish the shape of a tetromino figure.
     *
     */
    I, // Line
    O, // Square
    T, // T-shape
    S, // S-shape (left)
    Z, // Z-shape (right)
    L,  // L-shape (right)
    J, // J-shape (left)
};